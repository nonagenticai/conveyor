"""Extract the local coding action snapshot for the offline design prototype.

Run from any directory; the source remains the sibling coding node package.
This generates display data, not a new Conveyor action contract.
"""
import hashlib
import json
import re
from pathlib import Path

design = Path(__file__).resolve().parents[1]
source = design.parents[2] / 'n8n_separated_modules/n8n-nodes-coding/docs/openapi.json'
raw = source.read_bytes()
spec = json.loads(raw)
node_options = {}
for resource_file in (source.parent.parent / 'nodes/Coding/resources').glob('*.resource.ts'):
    resource = resource_file.read_text()
    parts = resource.split('options: [', 1)
    if len(parts) != 2:
        continue
    resource_match = re.search(r'resource: \["([^"]+)"\]', parts[0])
    if not resource_match:
        continue
    for option in re.findall(r'value: "([^"]+)"', parts[1].split('default:', 1)[0]):
        # Join identifiers only after removing naming-style separators. Never invent an alias.
        key = re.sub(r'[^a-z0-9]', '', option.lower())
        node_options[key] = (resource_match[1], option)


def resolve(schema):
    if '$ref' in schema:
        result = spec
        for segment in schema['$ref'].removeprefix('#/').split('/'):
            result = result.get(segment, {})
        return result
    return schema


def type_label(schema):
    schema = resolve(schema)
    if 'type' in schema:
        value = schema['type']
        return ' | '.join(value) if isinstance(value, list) else value
    alternatives = schema.get('anyOf', schema.get('oneOf', []))
    if alternatives:
        return ' | '.join(type_label(value) for value in alternatives)
    return 'object' if 'properties' in schema else 'value'


operations = []
for path, methods in spec['paths'].items():
    for method, op in methods.items():
        if method not in {'get', 'post', 'put', 'patch', 'delete'}:
            continue
        fields = []
        for param in op.get('parameters', []):
            param = resolve(param)
            if param.get('in') == 'header':
                continue
            fields.append(dict(name=param.get('name'), type=type_label(param.get('schema', {})), required=param.get('required', False), location=param.get('in')))
        body = resolve(op.get('requestBody', {}))
        schema = resolve(body.get('content', {}).get('application/json', {}).get('schema', {}))
        for name, field in schema.get('properties', {}).items():
            field = resolve(field)
            fields.append(dict(name=name, type=type_label(field), required=name in schema.get('required', []), location='body'))
        if body and not schema.get('properties'):
            fields.append(dict(name='requestBody', type=schema.get('type', 'object'), required=body.get('required', False), location='body'))
        node_resource, node_option = node_options.get(re.sub(r'[^a-z0-9]', '', op['operationId'].lower()), (None, None))
        operations.append(dict(id=op['operationId'], title=op.get('summary', op['operationId']), group=(op.get('tags') or ['Other'])[0], method=method.upper(), path=path, role=op.get('x-operation-role', 'unclassified'), verifies=op.get('x-verifies', []), fields=fields, n8nResource=node_resource, n8nOperation=node_option))

data = dict(source='../n8n_separated_modules/n8n-nodes-coding/docs/openapi.json', sha256=hashlib.sha256(raw).hexdigest(), count=len(operations), nodeOptionCount=sum(bool(op['n8nOperation']) for op in operations), operations=operations)
(design / 'coding-catalogue.js').write_text('// Generated by scripts/build-coding-catalogue.py. Local source snapshot.\nwindow.CODING_CATALOGUE = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print(f'Extracted {len(operations)} operations into coding-catalogue.js')
