-- The tenant inference-policy tables and the epoch row (alembic 0015).
CREATE TABLE tenant_inference_policy_version (
    tenant_id uuid NOT NULL,
    version integer NOT NULL,
    doc jsonb NOT NULL,
    doc_sha256 char(64) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    actor_kind text NOT NULL,
    actor_ref_hash text NOT NULL,
    PRIMARY KEY (tenant_id, version),
    CONSTRAINT ck_tipv_version_positive CHECK (version >= 1),
    CONSTRAINT ck_tipv_tenant_not_nil
        CHECK (tenant_id <> '00000000-0000-0000-0000-000000000000'::uuid)
);

CREATE TABLE tenant_inference_policy (
    tenant_id uuid PRIMARY KEY,
    active_version integer NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_tip_active_version FOREIGN KEY (tenant_id, active_version)
        REFERENCES tenant_inference_policy_version (tenant_id, version)
);

-- `sa.SmallInteger primary_key=True` made SQLAlchemy attach a sequence (the live dump carries
-- `policy_epoch_id_seq` and `DEFAULT nextval(...)`), not an identity column. Reproduce it.
CREATE SEQUENCE policy_epoch_id_seq
    AS smallint
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1;

CREATE TABLE policy_epoch (
    id smallint NOT NULL DEFAULT nextval('policy_epoch_id_seq'::regclass),
    epoch bigint NOT NULL DEFAULT '0'::bigint,
    CONSTRAINT ck_policy_epoch_single_row CHECK (id = 1)
);

ALTER SEQUENCE policy_epoch_id_seq OWNED BY policy_epoch.id;
-- Alembic adds the primary key as a separate named constraint; match it so the dump agrees.
ALTER TABLE policy_epoch ADD CONSTRAINT policy_epoch_pkey PRIMARY KEY (id);

INSERT INTO policy_epoch (id, epoch) VALUES (1, 0);

CREATE TABLE tenant_policy_audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL,
    action text NOT NULL,
    version integer,
    actor_kind text NOT NULL,
    actor_ref_hash text NOT NULL,
    at timestamptz NOT NULL DEFAULT now(),
    detail jsonb
);

CREATE INDEX ix_tenant_policy_audit_tenant_at ON tenant_policy_audit (tenant_id, at);
