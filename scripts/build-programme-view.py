#!/usr/bin/env python3
"""Render the programme's tracked GitHub issue from the seed and the issue registry.

One programme, one GitHub face: the issue this script writes is the human-readable table of
every project in `seed/programme.json` — status, tranche, what blocks it, its units and their
links. It is generated, never edited by hand; the body is deterministic, so a refresh changes it
only when a row changed.

The same rows are published for download by the service:
`https://conveyor.nonagentic.ai/design/data/programme.json` and `.csv`.

Run from any directory:

    python3 scripts/build-programme-view.py                    # print the body
    python3 scripts/build-programme-view.py --check-issue 450  # exit 1 when the issue is stale
    python3 scripts/build-programme-view.py --update 450       # write the body to the issue
    python3 scripts/build-programme-view.py --create           # create the issue once, then pin it

The status shown is the seed's `project.status`, derived by `scripts/programme_state.py`; the
issue never carries its own status logic.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEED_FILE = ROOT / "seed" / "programme.json"
ISSUES_FILE = ROOT / "docs" / "design" / "data" / "issues.json"

TITLE = "conveyor-buildout — the SPEC_V2 programme"
LABEL = "programme"
REPO = "nonagenticai/conveyor"

STATUS_ORDER = ["closed", "active", "draft", "archived"]
TRACK_ORDER = ["programme", "v2", "v1"]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def order_key(project: dict) -> tuple:
    key = project["key"]
    track = project.get("meta", {}).get("track", "")
    return (TRACK_ORDER.index(track) if track in TRACK_ORDER else 9, key)


def render(seed: dict, issues: list[dict]) -> str:
    by_number = {issue["number"]: issue for issue in issues}
    projects = sorted(seed["projects"], key=order_key)
    statuses = {project["key"]: project["status"] for project in projects}
    counts: dict[str, int] = {}
    for project in projects:
        counts[project["status"]] = counts.get(project["status"], 0) + 1

    lines: list[str] = [
        "<!-- generated by scripts/build-programme-view.py — do not edit by hand -->",
        "",
        f"**One programme, one record.** This issue is the table of every project in the "
        f"buildout: {len(projects)} projects across {len(set(p['meta'].get('track','') for p in projects))} tracks. "
        "The same rows download from the public design site as "
        "[programme.json](https://conveyor.nonagentic.ai/design/data/programme.json) and "
        "[programme.csv](https://conveyor.nonagentic.ai/design/data/programme.csv).",
        "",
        "Status is derived once, by `scripts/programme_state.py`: GitHub issue state outranks the "
        "design pack's coverage, which outranks the plan frontmatter. A project whose units are "
        "all closed reads `closed` even while its plan file still says draft.",
        "",
        "| Status | Projects |",
        "|---|---:|",
    ]
    for status in STATUS_ORDER:
        if counts.get(status):
            lines.append(f"| `{status}` | {counts[status]} |")
    lines += [
        "",
        "## Projects",
        "",
        "| Key | Project | Tranche | Status | Blocked by | Units | Links |",
        "|---|---|---:|---|---|---|---|",
    ]

    for project in projects:
        meta = project.get("meta", {})
        numbers = meta.get("issues", [])
        units = [by_number[number] for number in numbers if number in by_number]
        open_units = [issue for issue in units if issue["state"] == "OPEN"]
        claimed = [
            issue
            for issue in open_units
            if any(label["name"] == "status:claimed" for label in issue.get("labels", []))
        ]
        blocked_by = [
            dependency
            for dependency in meta.get("depends_on", [])
            if statuses.get(dependency) != "closed"
        ]
        unit_text = f"{len(open_units)} open / {len(claimed)} claimed / {len(numbers)} total"
        links = " · ".join(
            f"[#{number}]({by_number[number]['url']})" for number in numbers if number in by_number
        )
        if not links:
            links = "—"
        lines.append(
            "| {key} | {name} | {tranche} | `{status}` | {blocked} | {units} | {links} |".format(
                key=project["key"],
                name=project["name"].replace("|", "\\|"),
                tranche=meta.get("tranche", 0),
                status=project["status"],
                blocked=", ".join(blocked_by) if blocked_by else "—",
                units=unit_text,
                links=links,
            )
        )

    lines += [
        "",
        "---",
        "",
        f"Sources: `seed/programme.json` sha256 `{sha256(SEED_FILE)[:16]}` · "
        f"`docs/design/data/issues.json` sha256 `{sha256(ISSUES_FILE)[:16]}` · "
        "derivation `scripts/programme_state.py`.",
        "",
        "Refresh: `.github/workflows/issue-registry.yml` regenerates and updates this body on "
        "every push to `main`. A row that disagrees with the site's download is a defect in the "
        "generator, not in the table.",
        "",
    ]
    return "\n".join(lines)


def current_body(number: int) -> str:
    out = subprocess.run(
        ["gh", "issue", "view", str(number), "--repo", REPO, "--json", "body"],
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(out.stdout)["body"]


def existing_programme_issue() -> int | None:
    out = subprocess.run(
        [
            "gh",
            "issue",
            "list",
            "--repo",
            REPO,
            "--label",
            LABEL,
            "--state",
            "open",
            "--limit",
            "5",
            "--json",
            "number,title",
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    for row in json.loads(out.stdout):
        if row["title"].strip() == TITLE:
            return row["number"]
    return None


def create_issue(body: str) -> int:
    out = subprocess.run(
        [
            "gh",
            "issue",
            "create",
            "--repo",
            REPO,
            "--title",
            TITLE,
            "--label",
            LABEL,
            "--body-file",
            "-",
        ],
        input=body,
        capture_output=True,
        text=True,
        check=True,
    )
    return int(out.stdout.strip().rsplit("/", 1)[-1])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-issue", type=int, metavar="N", help="exit 1 when issue N is stale")
    parser.add_argument("--update", type=int, metavar="N", help="write the body to issue N")
    parser.add_argument(
        "--sync",
        action="store_true",
        help="find the tracked issue (create and pin it once), then update it only when stale",
    )
    args = parser.parse_args()

    seed = json.loads(SEED_FILE.read_text(encoding="utf-8"))
    issues = json.loads(ISSUES_FILE.read_text(encoding="utf-8")).get("issues", [])
    body = render(seed, issues)

    if args.check_issue is not None:
        if current_body(args.check_issue).strip() != body.strip():
            sys.exit(f"build-programme-view: issue #{args.check_issue} is stale")
        print(f"build-programme-view: issue #{args.check_issue} matches the seed")
        return

    if args.update is not None:
        subprocess.run(
            [
                "gh",
                "issue",
                "edit",
                str(args.update),
                "--repo",
                REPO,
                "--body-file",
                "-",
            ],
            input=body,
            text=True,
            check=True,
        )
        print(f"build-programme-view: updated issue #{args.update}")
        return

    if args.sync:
        number = existing_programme_issue()
        if number is None:
            number = create_issue(body)
            subprocess.run(
                ["gh", "issue", "pin", str(number), "--repo", REPO],
                capture_output=True,
                text=True,
            )
            print(f"build-programme-view: created and pinned issue #{number}")
            return
        if current_body(number).strip() == body.strip():
            print(f"build-programme-view: issue #{number} is current")
            return
        subprocess.run(
            ["gh", "issue", "edit", str(number), "--repo", REPO, "--body-file", "-"],
            input=body,
            text=True,
            check=True,
        )
        print(f"build-programme-view: updated issue #{number}")
        return

    sys.stdout.write(body)


if __name__ == "__main__":
    main()
